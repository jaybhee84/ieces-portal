import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { strFromU8, unzipSync } from "fflate";
import { createNutritionReportExcel, excelDate, nutritionReportFilename } from "../src/lib/nutritionReportExcel.mjs";

const meta = { gradeClassLabel: "Grade 4 - Test", dateOfWeighing: "06/09/2026", periodLabel: "Baseline", schoolYear: "2026-2027", schoolYearLabel: "Baseline SY 2026-2027" };
const learner = (name, sex, bmiStatus = "Normal", hfaStatus = "Normal") => ({ name, birthdate: "2016-02-29", report: { weightKg: 30.5, heightMeters: 1.43, heightSquaredMeters: 2.0449, bmi: 14.9, ageYearMonth: "10.10", sex, bmiStatus, hfaStatus } });
const read = (bytes) => Object.fromEntries(Object.entries(unzipSync(bytes)).filter(([name]) => name.endsWith(".xml")).map(([name, value]) => [name, strFromU8(value)]));
const value = (sheet, address) => new RegExp(`<c r="${address}"[^>]*>(.*?)</c>`).exec(sheet)?.[1];
const rows = [learner("ALPHA, Girl", "F", "Wasted"), learner("ZETA, Boy", "M"), learner("=A&B <Test>", "M", "Obese", "Tall")];
const bytes = createNutritionReportExcel(rows, meta, "TEST ADVISER");
const files = read(bytes);
const sheet = files["xl/worksheets/sheet1.xml"];
assert.equal(String.fromCharCode(...bytes.slice(0, 2)), "PK");
assert.match(sheet, /dimension ref="A1:N48"/);
assert.match(value(sheet, "B9"), /=A&amp;B &lt;Test&gt;/);
assert.match(value(sheet, "B11"), /ALPHA, Girl/);
assert.equal(value(sheet, "I9"), '<is><t xml:space="preserve">10.10</t></is>');
assert.equal(value(sheet, "E9"), "<v>30.5</v>");
assert.equal(value(sheet, "F9"), "<v>1.43</v>");
assert.equal(value(sheet, "D36"), "<v>2</v>");
assert.equal(value(sheet, "E36"), "<v>1</v>");
assert.equal(value(sheet, "F36"), "<v>3</v>");
assert.equal(value(sheet, "E38"), "<v>1</v>");
assert.equal(value(sheet, "D41"), "<v>1</v>");
assert.equal(value(sheet, "I40"), "<v>1</v>");
assert.match(value(sheet, "G46"), /TEST ADVISER/);
assert.doesNotMatch(Object.values(files).join(""), /POLIQUIT|ABDAH|Larrachochea|<f>/);
assert.equal(excelDate("06/09/2026"), 46182);
assert.equal(excelDate("2016-02-29"), 42429);
assert.equal(excelDate("2015-02-29"), null);
assert.equal(excelDate(""), null);
assert.equal(nutritionReportFilename(meta), "IECES_NS_Report_Baseline_Grade_4_Test_SY2026-2027.xlsx");

const manyRows = Array.from({ length: 60 }, (_, i) => learner(`LEARNER ${String(i + 1).padStart(2, "0")}`, i % 2 ? "F" : "M"));
const largeBytes = createNutritionReportExcel(manyRows, { ...meta, periodLabel: "Endline", schoolYearLabel: "Endline SY 2026-2027" }, "TEST ADVISER");
const large = read(largeBytes);
assert.match(large["xl/worksheets/sheet1.xml"], /dimension ref="A1:N83"/);
assert.match(large["xl/worksheets/sheet1.xml"], /mergeCell ref="G81:K81"/);
assert.equal(value(large["xl/worksheets/sheet1.xml"], "F71"), "<v>60</v>");
assert.match(large["xl/drawings/drawing1.xml"], /<xdr:row>69<\/xdr:row>/);
assert.match(large["xl/workbook.xml"], /\$N\$83/);
assert.match(large["xl/worksheets/sheet1.xml"], /fitToHeight="0"/);
const missing = learner("NO MEASUREMENT", "F", "—", "—");
missing.birthdate = "";
missing.report.weightKg = missing.report.heightMeters = missing.report.heightSquaredMeters = missing.report.bmi = null;
const missingSheet = read(createNutritionReportExcel([missing], meta, ""))["xl/worksheets/sheet1.xml"];
assert.match(missingSheet, /<c r="E9" s="17"\/>/);
assert.equal(value(missingSheet, "F36"), "<v>0</v>");
const emptySheet = read(createNutritionReportExcel([], meta, ""))["xl/worksheets/sheet1.xml"];
assert.equal(value(emptySheet, "F36"), "<v>0</v>");

const out = await mkdtemp(join(tmpdir(), "ieces-export-test-"));
await writeFile(join(out, "report.xlsx"), createNutritionReportExcel(manyRows.slice(0, 25), meta, "TEST ADVISER"));
await writeFile(join(out, "large-report.xlsx"), largeBytes);
console.log(`Export checks passed: layout, typed values, escaping, dates, tallies, missing data, 60 learners, and Endline.\nVisual QA fixtures: ${out}`);
